import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';

const base = process.argv[2] || 'http://127.0.0.1:7100';
const executablePath = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox', '--enable-gpu', '--use-angle=metal'] });
await mkdir('verification-shots', { recursive: true });
const report = { errors: [], notFound: [], views: [], stats: null, fileChooser: false };
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
page.on('pageerror', (error) => report.errors.push(String(error)));
page.on('console', (message) => { if (message.type() === 'error') report.errors.push(message.text()); });
page.on('response', (response) => { if (response.status() === 404) report.notFound.push(response.url()); });
await page.goto(`${base}/?capture=1&t=6.2`, { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.__SCENE_READY__ === true);
await page.screenshot({ path: 'verification-shots/desktop.png', fullPage: true });
await page.locator('.viewport').screenshot({ path: 'verification-shots/scene-6_2.png' });
await page.evaluate(() => window.__seek(10.1));
await page.locator('.viewport').screenshot({ path: 'verification-shots/scene-10_1.png' });
await page.locator('.viewport').screenshot({ path: 'verification-shots/scene-10_1.png', scale: 'css' });
report.stats = await page.evaluate(() => window.__getSceneStats());
const chooserPromise = page.waitForEvent('filechooser');
await page.locator('#choose-file').click();
const chooser = await chooserPromise;
report.fileChooser = chooser.isMultiple() === false;
const mobile = await browser.newPage({ viewport: { width: 375, height: 812 }, deviceScaleFactor: 1 });
mobile.on('pageerror', (error) => report.errors.push(String(error)));
mobile.on('console', (message) => { if (message.type() === 'error') report.errors.push(message.text()); });
await mobile.goto(`${base}/?capture=1&t=6.2`, { waitUntil: 'networkidle' });
await mobile.waitForFunction(() => window.__SCENE_READY__ === true);
await mobile.screenshot({ path: 'verification-shots/mobile.png', fullPage: true });
report.mobileOverflow = await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth);
await writeFile('verification-shots/report.json', JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
await browser.close();
if (report.errors.length || report.notFound.length || report.mobileOverflow || !report.fileChooser) process.exit(1);
